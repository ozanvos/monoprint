//! Regenerate bundled Studio previews: cargo run --release --example gui_thumbnails
use image::{RgbaImage, imageops::FilterType};
use monoprint::{Appearance, Renderer, Scale, Snippet, Style, Theme};
use std::{fs, io::Cursor, path::Path};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let output = Path::new("apps/monoprint-gui/assets/themes");
    fs::create_dir_all(output)?;
    let renderer = Renderer::new();
    let snippet = Snippet::new(
        "const theme = \"Monoprint\";\n\nfunction print(code: string) {\n  return render(code, { theme });\n}",
    ).language("tsx".parse()?);
    let mut catalog = String::from("// Generated by examples/gui_thumbnails.rs.\n&[\n");
    let mut light_catalog = String::from("// Generated by examples/gui_thumbnails.rs.\n&[\n");
    let mut total_bytes = 0;
    let mut total_pixels = 0;
    for theme in Theme::all() {
        for appearance in [theme.default_appearance(), Appearance::Light] {
            if !theme.supports(appearance) {
                continue;
            }
            let suffix = if appearance == theme.default_appearance() {
                ""
            } else {
                "-light"
            };
            let name = format!("{}{suffix}", theme.id());
            let entry = format!(
                "    (\"{}\", include_bytes!(\"{name}.png\")),\n",
                theme.id()
            );
            if appearance == Appearance::Light {
                light_catalog.push_str(&entry);
            }
            if suffix.is_empty() {
                catalog.push_str(&entry);
            }
            let style = Style::new(theme)
                .appearance(appearance)
                .width(480)
                .padding(32);
            let encoded = renderer.png(&snippet, &style, Scale::X1)?;
            let mut decoder = png::Decoder::new(Cursor::new(encoded));
            decoder.set_transformations(png::Transformations::EXPAND | png::Transformations::ALPHA);
            let mut reader = decoder.read_info()?;
            let mut pixels = vec![0; reader.output_buffer_size().unwrap()];
            let info = reader.next_frame(&mut pixels)?;
            assert_eq!(info.color_type, png::ColorType::Rgba);
            let image = RgbaImage::from_raw(info.width, info.height, pixels).unwrap();
            let height = (info.height as f64 * 256. / info.width as f64).round() as u32;
            let image = image::imageops::resize(&image, 256, height, FilterType::Lanczos3);
            let mut bytes = Vec::new();
            {
                let mut encoder = png::Encoder::new(&mut bytes, image.width(), image.height());
                encoder.set_color(png::ColorType::Rgba);
                encoder.set_depth(png::BitDepth::Eight);
                encoder.set_compression(png::Compression::High);
                encoder.write_header()?.write_image_data(image.as_raw())?;
            }
            total_bytes += bytes.len();
            total_pixels += image.width() * image.height();
            fs::write(output.join(format!("{name}.png")), bytes)?;
            // The preferred variant is already light for a light-only palette.
            if theme.default_appearance() == Appearance::Light {
                break;
            }
        }
    }
    catalog.push_str("]\n");
    fs::write(output.join("catalog.rs"), catalog)?;
    light_catalog.push_str("]\n");
    fs::write(output.join("catalog-light.rs"), light_catalog)?;
    println!(
        "{} themes with appearance previews: {} encoded bytes, {} decoded RGBA bytes",
        Theme::all().len(),
        total_bytes,
        total_pixels * 4
    );
    Ok(())
}
